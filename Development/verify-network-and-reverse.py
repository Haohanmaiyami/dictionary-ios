#!/usr/bin/env python3
"""Exercise real Swift error handling and Russian-source articles without network I/O."""
from pathlib import Path
import os
import argparse
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--fixtures', type=Path, help='Optional SearchResponse JSON generated by the backend')
args = parser.parse_args()
source = '\n'.join((ROOT / path).read_text() for path in [
    'Models/Entry.swift', 'Models/SavedEntry.swift', 'Models/SearchResponse.swift',
    'Models/AIModels.swift', 'Network/APIService.swift', 'Stores/FavoritesStore.swift',
])
source += r'''
@main
struct NetworkAndReverseChecks {
    static func main() async throws {
        let requestID = "7617a76f-2821-4e33-a21e-f4de9591391c"
        let url = URL(string: "https://example.invalid/no-network-request")!
        let response = HTTPURLResponse(url: url, statusCode: 403, httpVersion: nil,
            headerFields: ["X-Request-ID": requestID])!
        do {
            try APIService.validateDictionaryResponse(response)
            preconditionFailure("A dictionary HTTP failure was accepted")
        } catch let error as APIHTTPError {
            let text = NetworkErrorPresentation.message(for: error)!
            precondition(text.contains("HTTP 403") && text.contains(requestID))
        }
        try APIService.validateDictionaryResponse(HTTPURLResponse(url: url, statusCode: 200,
            httpVersion: nil, headerFields: nil)!)
        let invalidID = HTTPURLResponse(url: url, statusCode: 500, httpVersion: nil,
            headerFields: ["X-Request-ID": "private-text-not-a-uuid"])!
        precondition(NetworkErrorPresentation.requestID(from: invalidID) == nil)
        let noID = HTTPURLResponse(url: url, statusCode: 500, httpVersion: nil, headerFields: nil)!
        precondition(NetworkErrorPresentation.requestID(from: noID) == nil)
        precondition(!NetworkErrorPresentation.withRequestID("error", "private-text").contains("private-text"))
        print("PASS: dictionary HTTP status and optional validated request ID survive without disclosing arbitrary headers")

        let rateLimit = HTTPURLResponse(url: url, statusCode: 429, httpVersion: nil,
            headerFields: ["Retry-After": "61", "X-Request-ID": requestID])!
        do {
            try APIService.validateAIResponse(rateLimit)
            preconditionFailure("An AI rate limit was accepted")
        } catch let error as AIServiceError {
            guard case let .http(status, retryAfter, id) = error else { preconditionFailure() }
            precondition(status == 429 && retryAfter == 61 && id == requestID)
            let text = NetworkErrorPresentation.message(for: error)!
            precondition(text.contains("2 мин.") && text.contains("HTTP 429") && text.contains(requestID))
        }
        try APIService.validateAIResponse(HTTPURLResponse(url: url, statusCode: 200,
            httpVersion: nil, headerFields: nil)!)
        precondition(NetworkErrorPresentation.message(for: URLError(.cancelled)) == nil)
        precondition(NetworkErrorPresentation.message(for: CancellationError()) == nil)
        for code in [URLError.Code.timedOut, .notConnectedToInternet, .cannotConnectToHost,
                     .cannotFindHost, .dnsLookupFailed, .networkConnectionLost,
                     .secureConnectionFailed, .serverCertificateUntrusted,
                     .serverCertificateHasBadDate, .serverCertificateNotYetValid,
                     .serverCertificateHasUnknownRoot, .appTransportSecurityRequiresSecureConnection,
                     .badServerResponse] {
            let error = URLError(code, userInfo: [NSLocalizedDescriptionKey: "secret-message",
                                                 NSURLErrorFailingURLErrorKey: url])
            let text = NetworkErrorPresentation.message(for: error)!
            precondition(text.contains(String(code.rawValue)))
            precondition(!text.contains("secret-message") && !text.contains("example.invalid"))
        }
        precondition(NetworkErrorPresentation.message(for: URLError(.secureConnectionFailed)) !=
                     NetworkErrorPresentation.message(for: URLError(.serverCertificateUntrusted)))
        let decodeError = DecodingError.dataCorrupted(.init(codingPath: [], debugDescription: "private-response"))
        precondition(!NetworkErrorPresentation.message(for: decodeError)!.contains("private-response"))
        print("PASS: AI retry/request ID, cancellation, numeric transport/TLS errors and private-data suppression")

        let decoder = JSONDecoder()
        let oldJSON = #"{"id":1,"hanzi":"工作","pinyin":"gōngzuò","ru":"работа","examples":"пример"}"#
        let old = try decoder.decode(Entry.self, from: Data(oldJSON.utf8))
        precondition(!old.isRussianHeadword && old.displayHeadword == "工作")
        precondition(old.displayPinyin == "gōngzuò" && old.previewText == "работа")
        let chinesePreview = Entry(id: 7, hanzi: "甲", pinyin: nil, ru: "один<br>два", pos: nil, examples: nil)
        precondition(chinesePreview.previewText == "один два")
        let savedOld = try decoder.decode(SavedEntry.self, from: Data(oldJSON.utf8))
        precondition(savedOld.toEntry().displayHeadword == "工作")
        // Synthetic distinct definitions guard against displaying only the first Chinese run.
        let reverseJSON = #"{"id":2,"hanzi":"工作","pinyin":"gōngzuò","ru":"работа","headword":"работа","headword_language":"ru","examples":"legacy body","article":{"version":2,"source":{"language":"ru","headword":"работа","dictionary":"bruks"},"blocks":[{"level":1,"kind":"definition","number":"1","text":"工作; 劳动","references":[]},{"level":2,"kind":"example","text":"工作很忙","references":[]},{"level":1,"kind":"definition","number":"2","text":"作品; 作业","references":[]}]}}"#
        let reverse = try decoder.decode(Entry.self, from: Data(reverseJSON.utf8))
        precondition(reverse.isRussianHeadword && reverse.displayHeadword == "работа")
        precondition(reverse.displayPinyin == nil)
        precondition(reverse.previewText == "1) 工作; 劳动\n工作很忙\n2) 作品; 作业")
        precondition(reverse.hanzi == "工作" && reverse.ru == "работа")
        let saved = SavedEntry(from: reverse)
        let savedData = try JSONEncoder().encode(saved)
        let restored = try decoder.decode(SavedEntry.self, from: savedData)
        precondition(saved == restored && restored.toEntry().article == reverse.article)
        precondition(restored.toEntry().displayHeadword == "работа" && restored.toEntry().displayPinyin == nil)
        precondition(restored.toEntry().previewText == reverse.previewText)
        let savedObject = try JSONSerialization.jsonObject(with: savedData) as! [String: Any]
        precondition(savedObject["headword_language"] as? String == "ru")
        print("PASS: explicit Russian headword, all article paragraphs, saved/history round trips, legacy Chinese compatibility")

        let fallback = try decoder.decode(Entry.self, from: Data(#"{"id":3,"hanzi":"工作","ru":"работа","headword":"работа","headword_language":"ru","examples":"工作; 劳动<br>作品; 作业"}"#.utf8))
        precondition(fallback.previewText == "工作; 劳动\n作品; 作业")
        for metadata in [#""headword":42,"headword_language":"ru""#,
                         #""headword":"работа","headword_language":42"#,
                         #""headword":"работа","headword_language":"unknown""#,
                         #""headword":" ","headword_language":"ru""#] {
            let json = "{\"id\":4,\"hanzi\":\"工作\",\"ru\":\"работа\"," + metadata + "}"
            let malformed = try decoder.decode(Entry.self, from: Data(json.utf8))
            precondition(!malformed.isRussianHeadword && malformed.displayHeadword == "工作")
        }
        let reference = try await DictionaryReferenceResolver.resolve(target: "работа") { _ in [old, reverse] }
        precondition(reference.id == reverse.id)
        let chineseReference = try await DictionaryReferenceResolver.resolve(target: "工作") { _ in [reverse, old] }
        precondition(chineseReference.id == old.id)
        print("PASS: no guessed provenance, malformed metadata fallback, original Russian reference lookup")
        let suite = "dictionary-network-checks-" + UUID().uuidString
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        let outdated = Entry(id: reverse.id, hanzi: reverse.hanzi, pinyin: reverse.pinyin,
                             ru: reverse.ru, pos: nil, examples: nil)
        try defaults.set(JSONEncoder().encode([SavedEntry(from: old), SavedEntry(from: outdated)]),
                         forKey: "favorite_entries")
        let bookmarks = FavoritesStore(defaults: defaults)
        bookmarks.refreshIfSaved(reverse)
        precondition(bookmarks.items.map(\.id) == [old.id, reverse.id])
        precondition(bookmarks.items.last?.toEntry().displayHeadword == "работа")
        precondition(bookmarks.items.last?.toEntry().previewText == reverse.previewText)
        bookmarks.refreshIfSaved(reverse)
        bookmarks.refreshIfSaved(fallback) // Not a favorite; must remain absent.
        precondition(bookmarks.items.map(\.id) == [old.id, reverse.id])
        precondition(FavoritesStore(defaults: defaults).items == bookmarks.items)
        print("PASS: fetching full articles refreshes existing favorites in place, persists metadata, and never adds/deletes bookmarks")

        if CommandLine.arguments.count > 1 {
            let data = try Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[1]))
            let api = try decoder.decode(SearchResponse.self, from: data)
            precondition(!api.results.isEmpty)
            for entry in api.results {
                precondition(entry.isRussianHeadword)
                precondition(entry.displayHeadword == entry.headword)
                precondition(entry.displayPinyin == nil)
                guard let article = entry.article else { preconditionFailure("Backend article was discarded") }
                precondition(entry.previewText == article.rows.map(\.displayText).joined(separator: "\n"))
                precondition(!entry.previewText.isEmpty && entry.previewText != entry.displayHeadword)
                let saved = SavedEntry(from: entry)
                let roundTrip = try decoder.decode(SavedEntry.self, from: JSONEncoder().encode(saved))
                precondition(roundTrip.toEntry().previewText == entry.previewText)
                precondition(roundTrip.toEntry().headword == entry.headword)
            }
            print("PASS: \(api.results.count) real backend reverse articles decode, render all paragraphs and survive saved-entry round trips")
        }
        print("No app launch, server request or signing was performed.")
    }
}
'''
with tempfile.TemporaryDirectory(prefix='dictionary-network-checks-') as folder:
    path = Path(folder)
    swift = path / 'Checks.swift'
    swift.write_text(source)
    binary = path / 'checks'
    env = os.environ.copy()
    xcode = Path('/Applications/Xcode.app/Contents/Developer')
    if xcode.is_dir():
        env.setdefault('DEVELOPER_DIR', str(xcode))
    subprocess.run(['/usr/bin/xcrun', 'swiftc', '-parse-as-library', str(swift), '-o', str(binary)],
                   env=env, check=True)
    command = [str(binary)]
    if args.fixtures:
        command.append(str(args.fixtures.resolve(strict=True)))
    subprocess.run(command, check=True)
